const dicts: Record<Language, Dict> = { nl, en };

type Leaves<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : Leaves<T[K], `${P}${K}.`>;
}[keyof T & string];

export type TKey = Leaves<Dict>;
export type TFn = (key: TKey, params?: Record<string, string | number>) => string;

export function translate(lang: Language, key: TKey, params?: Record<string, string | number>): string {
  let node: unknown = dicts[lang];
  for (const part of key.split(".")) node = (node as Record<string, unknown>)?.[part];
  let text = typeof node === "string" ? node : key;
  if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

/** Translation function bound to the current interface language. */
export function useT(): TFn {
  const lang = useApp((s) => s.settings.uiLanguage);
  return useCallback((key, params) => translate(lang, key, params), [lang]);
}

